static void i2c_scan(I2C_HandleTypeDef *h, const char *name)
{
  printf("%s scan:", name);
  for (uint8_t a = 1; a < 128; a++)
    if (HAL_I2C_IsDeviceReady(h, a << 1, 2, 5) == HAL_OK) printf(" 0x%02X", a);
  printf("\r\n");
}

static float mcp_temp(uint8_t reg)
{
  uint8_t b[2] = {0};
  if (HAL_I2C_Master_Transmit(&hi2c3, MCP_ADDR, &reg, 1, 50) != HAL_OK)
    return -999.0f;
  if (HAL_I2C_Master_Receive(&hi2c3, MCP_ADDR, b, 2, 50) != HAL_OK)
    return -998.0f;
  return (int16_t)((b[0] << 8) | b[1]) * 0.0625f;
}
